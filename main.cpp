#include <string>
#include <vector>

void count_vowels() {
    std::string text = "prism bridge";
    int vowels = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        char ch = text[i];
        if (ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u') vowels += 1;
    }
    (void)vowels;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

void min_of_two() {
    int a = 33, b = 57;
    int m = (a < b) ? a : b;
    (void)m;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

extern "C" int lucid_boulder();
extern "C" void placid_willow();
extern "C" void eager_ripple();
extern "C" void lucid_beacon();
extern "C" void mellow_marble();

int main() {
    count_vowels();
    least_multiple();
    min_of_two();
    collect_triples();
    placid_willow();
    eager_ripple();
    lucid_beacon();
    mellow_marble();
    return lucid_boulder();
}
